/**
 * Single invoice renderer → self-contained HTML (fonts embedded, no network).
 * Used for the in-app preview (iframe) AND the PDF (headless Chromium), so
 * the on-screen preview and the downloaded PDF are identical.
 * Vendor-provided text is HTML-escaped and never translated or rewritten.
 */

const esc = (s: unknown) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/** Isolates free text (any script) so it never reorders the surrounding layout. */
const bdi = (s: unknown) => `<bdi>${esc(s)}</bdi>`;

